const dictionaries = { en, fr, ar };

export function translate(lang, key, vars) {
  const dictionary = dictionaries[lang] || dictionaries.en;
  let value = dictionary[key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function hasLanguage(lang) {
  return Boolean(dictionaries[lang]);
}

export function languageLabel(lang) {
  return LANGUAGES.find((item) => item.code === lang)?.label || lang;
}

export function languageNameForPrompt(lang) {
  return {
    en: 'English',
    fr: 'French',
    ar: 'Arabic',
  }[lang] || 'English';
}
